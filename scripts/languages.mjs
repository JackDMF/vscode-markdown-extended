#!/usr/bin/env node
/**
 * Writes src/editor/languages.ts: the languages the installed highlight.js
 * highlights — each id, its display name and its aliases — for the code
 * block's Language… completions. The page bundle carries the list, not the
 * 1 MB library. `test/unit/editor/languages.test.ts` compares the generated
 * module with the package, so a highlight.js bump that changes the list fails
 * the build until `npm run languages` runs again.
 */
import { createRequire } from 'module';
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const require = createRequire(import.meta.url);
const hljs = require('highlight.js');
const { version } = require('highlight.js/package.json');

const languages = hljs.listLanguages()
    .map(id => {
        const language = hljs.getLanguage(id);
        return { id, name: language.name ?? id, aliases: [...(language.aliases ?? [])] };
    })
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const lines = [
    `// Generated by scripts/languages.mjs from highlight.js ${version} — do not edit; run \`npm run languages\`.`,
    '',
    '/** One language highlight.js highlights: the id a fence names, its display name, the other words that name it. */',
    'export interface Language {',
    '    readonly id: string;',
    '    readonly name: string;',
    '    readonly aliases: readonly string[];',
    '}',
    '',
    '/** Every language the installed highlight.js highlights, by id. */',
    'export const LANGUAGES: readonly Language[] = [',
    ...languages.map(l => `    { id: ${JSON.stringify(l.id)}, name: ${JSON.stringify(l.name)}, aliases: ${JSON.stringify(l.aliases)} },`),
    '];',
    '',
];

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'editor', 'languages.ts');
writeFileSync(out, lines.join('\n'));
console.log(`${languages.length} languages from highlight.js ${version} → ${out}`);
